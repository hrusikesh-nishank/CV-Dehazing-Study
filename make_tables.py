"""Write the report's LaTeX tables (booktabs) from a results folder -> <res_dir>/tables.tex

  python make_tables.py                                   # full protocol (results/)
  python make_tables.py --res_dir results_quick --ft_models dehazeformer-t dehazeformer-b deanet

Tables
  1. Zero-shot comparison with published models (all evaluated by OUR protocol)
  2. Image-formation ablation (main model, mean +- std over seeds)
  3. The pre-registered claim: cost of removing the camera vs removing heterogeneity
  4. Second architecture (generality)
  5. Fine-tuning official checkpoints on each data source
Missing results are printed as "--" so the file always compiles.
"""
import argparse
import math
from pathlib import Path

from stats import SETS, bootstrap, groups, summarize

ARM_DESC = {
    "B0": "RESIDE-OTS pairs (official synthesis)",
    "N0": "sRGB ASM, grey airlight (our depth, $V$)",
    "R0": "sRGB ASM, sky-coloured airlight",
    "R1": "+ linear-radiance compositing",
    "R2": "+ post-haze shot/read noise",
    "R3": "+ randomised ISP + JPEG (full camera)",
    "R3N": "R3 without sensor noise (linear + ISP + JPEG)",
    "R4": "+ forward-scatter blur",
    "S0": "camera on sRGB composite (no linear)",
    "H": "sRGB ASM + heterogeneous $\\beta$",
    "R3H": "full camera + heterogeneous $\\beta$",
}
ARM_ORDER = ["B0", "N0", "R0", "R1", "R2", "R3", "R3N", "R4", "S0", "H", "R3H"]
PRETRAINED = [
    ("pre__hazy-input", "Hazy input", "--"),
    ("pre__dcp", "DCP~\\cite{he2009dcp}", "none"),
    ("pre__dehazeformer-t-outdoor", "DehazeFormer-T~\\cite{song2023dehazeformer}", "RESIDE-OTS"),
    ("pre__dehazeformer-s-outdoor", "DehazeFormer-S~\\cite{song2023dehazeformer}", "RESIDE-OTS"),
    ("pre__dehazeformer-b-outdoor", "DehazeFormer-B~\\cite{song2023dehazeformer}", "RESIDE-OTS"),
    ("pre__dehazeformer-m-outdoor", "DehazeFormer-M~\\cite{song2023dehazeformer}", "RESIDE-OTS"),
    ("pre__dehazeformer-t-reside6k", "DehazeFormer-T~\\cite{song2023dehazeformer}", "RESIDE-6K"),
    ("pre__dehazeformer-b-reside6k", "DehazeFormer-B~\\cite{song2023dehazeformer}", "RESIDE-6K"),
    ("pre__deanet-ots", "DEA-Net~\\cite{chen2024deanet}", "RESIDE-OTS"),
    ("pre__hazeflow-iccv25", "HazeFlow~\\cite{shin2025hazeflow} (published outputs)", "RIDCP500 + real unpaired (URHI/RTTS)"),
]
OFFICIAL = {"deanet": "pre__deanet-ots"}          # default: pre__<model>-outdoor


def f(x, d=2, std=None):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    s = f"{x:.{d}f}"
    if std is not None and not (isinstance(std, float) and math.isnan(std)):
        s += f"$\\pm${std:.{d}f}"
    return s


def row_metrics(r, with_std=False):
    cells = []
    for s in SETS:
        cells += [f(r.get(f"{s}_psnr"), 2, r.get(f"{s}_psnr_std") if with_std else None), f(r.get(f"{s}_ssim"), 3)]
    cells += [f(r.get("RTTS_mAP50"), 1, r.get("RTTS_mAP50_std") if with_std else None),
              f(r.get("musiq"), 2), f(r.get("clipiqa"), 3), f(r.get("brisque"), 2), f(r.get("niqe"), 2)]
    return cells


HEAD = ("& \\multicolumn{2}{c}{O-HAZE} & \\multicolumn{2}{c}{NH-HAZE} & \\multicolumn{2}{c}{Dense-Haze} "
        "& \\multicolumn{5}{c}{RTTS (no reference)} \\\\\n"
        "\\cmidrule(lr){%d-%d}\\cmidrule(lr){%d-%d}\\cmidrule(lr){%d-%d}\\cmidrule(lr){%d-%d}\n"
        "%s & PSNR$\\uparrow$ & SSIM$\\uparrow$ & PSNR$\\uparrow$ & SSIM$\\uparrow$ & PSNR$\\uparrow$ & SSIM$\\uparrow$ "
        "& mAP$_{50}\\uparrow$ & MUSIQ$\\uparrow$ & CLIPIQA$\\uparrow$ & BRISQUE$\\downarrow$ & NIQE$\\downarrow$ \\\\\n\\midrule\n")


def tab(caption, label, n0, lead_head, rows):
    spec = "l" * n0 + "c" * 11
    h = HEAD % (n0 + 1, n0 + 2, n0 + 3, n0 + 4, n0 + 5, n0 + 6, n0 + 7, n0 + 11, lead_head)
    body = "".join(" & ".join(r) + " \\\\\n" for r in rows)
    return (f"\\begin{{table*}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n"
            f"\\resizebox{{\\textwidth}}{{!}}{{%\n\\begin{{tabular}}{{{spec}}}\n\\toprule\n"
            + "&" * (n0 - 1) + h + body + "\\bottomrule\n\\end{tabular}}\n\\end{table*}\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--res_dir", default="results")
    ap.add_argument("--model", default="dehazeformer-t")
    ap.add_argument("--arch2", default="gunet-t")
    ap.add_argument("--ft_models", nargs="*", default=["dehazeformer-t", "dehazeformer-b", "deanet"])
    ap.add_argument("--note", default="", help="extra sentence appended to every caption (e.g. quick-protocol settings)")
    a = ap.parse_args()
    G = groups(a.res_dir)
    S = {k: summarize(k, v) for k, v in G.items()}
    note = (" " + a.note) if a.note else ""
    out = ["% generated by make_tables.py -- do not edit by hand\n"]

    # 1. comparison with published models
    rows = [[n, tr] + row_metrics(S[k]) for k, n, tr in PRETRAINED if k in S]
    for arm in ["R0", "R3"]:
        k = f"{a.model}__{arm}"
        if k in S:
            rows.append([f"\\textbf{{Ours}}: {a.model} trained on {arm}", "ours (OTS clean images)"] + row_metrics(S[k], True))
    for m in a.ft_models:
        k = f"{m}__R3_ft"
        if k in S:
            rows.append([f"\\textbf{{Ours}}: {m} (official) fine-tuned on R3", "official + ours"] + row_metrics(S[k], True))
    out.append(tab("Zero-shot transfer to real haze. All rows are evaluated with one protocol (long side 1024, same "
                   "metric code, VOC mAP$_{50}$ with YOLOv8m); no numbers are copied from other papers." + note,
                   "tab:sota", 2, "Method & Training data", rows))

    # 2. ablation
    rows = []
    for arm in ARM_ORDER:
        k = f"{a.model}__{arm}"
        if k in S:
            rows.append([arm, ARM_DESC[arm], str(S[k].get("seeds", 0))] + row_metrics(S[k], True))
    out.append(tab(f"Image-formation ablation ({a.model}; identical clean images, depth, $V$, $A$, crops and schedule; "
                   "mean$\\pm$std over seeds where more than one seed was run)." + note,
                   "tab:ablation", 3, "Arm & Synthesis & seeds", rows))

    # 3. claim
    lines = ["\\begin{table}[t]\n\\centering\n\\caption{Pre-registered test: PSNR cost (dB) of removing each component "
             "from the full pipeline (R3H). 95\\% paired-bootstrap CI over images, seed-averaged." + note + "}\n"
             "\\label{tab:claim}\n\\begin{tabular}{lcc}\n\\toprule\n"
             "Set & $-$camera (R3H$\\to$H) & $-$heterogeneity (R3H$\\to$R3) \\\\\n\\midrule\n"]
    for s in SETS:
        try:
            c = bootstrap(f"{a.model}__R3H", f"{a.model}__H", s, res_dir=a.res_dir)
            h = bootstrap(f"{a.model}__R3H", f"{a.model}__R3", s, res_dir=a.res_dir)
            lines.append(f"{s} & {c['delta']:+.2f} [{c['lo']:+.2f},{c['hi']:+.2f}] & {h['delta']:+.2f} [{h['lo']:+.2f},{h['hi']:+.2f}] \\\\\n")
        except Exception:
            lines.append(f"{s} & -- & -- \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n\n")
    out.append("".join(lines))

    # 4. second architecture
    rows = [[arm, ARM_DESC[arm]] + row_metrics(S[f"{a.arch2}__{arm}"], True) for arm in ARM_ORDER if f"{a.arch2}__{arm}" in S]
    out.append(tab(f"Generality: the same comparison with a second architecture ({a.arch2})." + note, "tab:arch2",
                   2, "Arm & Synthesis", rows))

    # 5. fine-tuning official checkpoints
    rows = []
    for m in a.ft_models:
        k0 = OFFICIAL.get(m, f"pre__{m}-outdoor")
        if k0 in S:
            rows.append([m, "official (no fine-tuning)"] + row_metrics(S[k0]))
        for arm in ["B0", "N0", "R0", "R3"]:
            k = f"{m}__{arm}_ft"
            if k in S:
                rows.append([m, f"+ fine-tune on {arm}"] + row_metrics(S[k], True))
    out.append(tab("Fine-tuning official RESIDE-OTS checkpoints for the same number of steps on each data source. "
                   "B0 controls for extra training on the same clean images." + note, "tab:ft", 2, "Model & Data", rows))

    Path(a.res_dir).mkdir(exist_ok=True)
    (Path(a.res_dir) / "tables.tex").write_text("".join(out), encoding="utf-8")
    print(f"wrote {Path(a.res_dir) / 'tables.tex'}")


if __name__ == "__main__":
    main()
